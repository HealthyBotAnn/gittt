def analyze_results(results):
    text = "🔬 АНАЛИЗ ВАШИХ АНАЛИЗОВ\n\n"
    found = False
    for name, val in results.items():
        name_lower = name.lower()
        for key, norm in ANALYSIS_NORMS.items():
            if key in name_lower:
                found = True
                low, high = norm["range"]
                if val < low:
                    status = f"⚠️ НИЖЕ НОРМЫ ({low}-{high})\n  {norm['low']}"
                elif val > high:
                    status = f"⚠️ ВЫШЕ НОРМЫ ({low}-{high})\n  {norm['high']}"
                else:
                    status = f"✅ В НОРМЕ ({low}-{high})"
                text += f"📊 {name}: {val}\n  {status}\n\n"
                break
    if not found:
        text += "Не нашёл знакомых показателей.\n"
        text += "Попробуйте формат: Ферритин – 12\n"
        text += "Гемоглобин – 110\nи т.д.\n\n"
    text += "⚠️ Это не диагноз. К врачу — обязательно."
    return text

