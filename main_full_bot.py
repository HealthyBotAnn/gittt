def parse_analysis_text(text):
    lines = text.strip().split("\n")
    results = {}
    for line in lines:
        for marker in ["–", "—", "-", ":"]:
            if marker in line:
                parts = line.split(marker)
                if len(parts) >= 2:
                    name = parts[0].strip()
                    val = parts[1].strip()
                    num_match = re.search(r"[\d.]+", val.replace(",", "."))
                    if num_match:
                        results[name] = float(num_match.group())
                        break
    return results

