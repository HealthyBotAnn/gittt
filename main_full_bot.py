def get_dosha_result(scores):
    max_val = max(scores.values())
    if list(scores.values()).count(max_val) > 1:
        tied = [k for k, v in scores.items() if v == max_val]
        return f"Смешанная: {' + '.join(tied)}"
    return max(scores, key=scores.get)

