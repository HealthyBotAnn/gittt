def detect_emotion(text):
    text_lower = text.lower()
    if any(t in text_lower for t in EMOTION_PATTERNS["crisis"]):
        return "crisis"
    if any(t in text_lower for t in EMOTION_PATTERNS["depression"]):
        return "depression"
    if any(t in text_lower for t in EMOTION_PATTERNS["grief"]):
        return "grief"
    if any(t in text_lower for t in EMOTION_PATTERNS["anxiety"]):
        return "anxiety"
    if any(t in text_lower for t in EMOTION_PATTERNS["anger"]):
        return "anger"
    if any(t in text_lower for t in EMOTION_PATTERNS["joy"]):
        return "joy"
    if any(t in text_lower for t in EMOTION_PATTERNS["loneliness"]):
        return "loneliness"
    return None

def log_emotion(chat_id, emotion, text):
    user_data = load_user(chat_id)
    if "emotion_log" not in user_data:
        user_data["emotion_log"] = []
    user_data["emotion_log"].append({
        "date": datetime.now().strftime("%Y-%m-%d %H:%M"),
        "emotion": emotion,
        "text": text[:200],
    })
    if len(user_data["emotion_log"]) > 100:
        user_data["emotion_log"] = user_data["emotion_log"][-100:]
    save_user(chat_id, user_data)

