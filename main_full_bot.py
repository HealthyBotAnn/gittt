def get_age(birth_date):
    try:
        birth = datetime.strptime(birth_date, "%d.%m.%Y")
        today = datetime.now()
        age = today.year - birth.year
        if (today.month, today.day) < (birth.month, birth.day):
            age -= 1
        return age
    except:
        return None

